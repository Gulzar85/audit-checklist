"""Reporting constants (Phase 19): limits, formats, statuses."""

from __future__ import annotations

from django.db import models
from django.utils.translation import gettext_lazy as _

# --- limits (server-controlled) --------------------------------------------------------------------------------------------------------
DEFAULT_RANGE_DAYS = 90  # when no date is given
MAX_RANGE_DAYS = 366  # the longest period a single report run may cover
PAGE_SIZE = 25
MAX_PAGE_SIZE = 100
MAX_ROWS = 20000  # hard cap of rows in one result / export
SYNC_EXPORT_MAX_ROWS = 2000  # above this an export is generated by a Phase 18 job
MAX_SUMMARY_GROUPS = 2000
FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r", "\n")


class Format(models.TextChoices):
    CSV = "csv", _("CSV")
    XLSX = "xlsx", _("Excel (XLSX)")
    PDF = "pdf", _("PDF")


class RunStatus(models.TextChoices):
    QUEUED = "queued", _("Queued")
    RUNNING = "running", _("Running")
    SUCCEEDED = "succeeded", _("Ready")
    FAILED = "failed", _("Failed")
    EXPIRED = "expired", _("Expired")


class Visibility(models.TextChoices):
    PRIVATE = "private", _("Only me")
    ORGANIZATION = "organization", _("Everyone in the organization who may run it")


class Origin(models.TextChoices):
    USER = "user", _("Requested by a user")
    SCHEDULE = "schedule", _("Scheduled")
