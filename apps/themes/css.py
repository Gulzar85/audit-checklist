"""Turn validated tokens into CSS custom properties - and nothing else.

The output of this module is the *entire* dynamic stylesheet of the platform.  It contains
only ``--custom-property: value`` declarations inside three fixed rule blocks, built from
:mod:`apps.themes.tokens` (whose values are re-serialised from parsed data).  There is no
code path that can place user text into a selector, a property name or an at-rule.

Delivery is a same-origin ``<link rel="stylesheet">`` - not an inline ``<style>`` - so the
strict CSP (``style-src 'self' 'nonce-…'``) is untouched.
"""

from __future__ import annotations

import hashlib

from . import tokens as tk
from .constants import STATUS_BORDER_PERCENT, STATUS_SOFT_PERCENT, STATUS_TEXT_PERCENT

LIGHT_SELECTOR = ':root, [data-theme="light"]'
DARK_SELECTOR = '[data-theme="dark"]'
SYSTEM_SELECTOR = '[data-theme="system"]'

_HEADER = "/* Generated from validated design tokens. Do not edit. */\n"


def _declarations(variables: dict[str, str], indent: str = "  ") -> str:
    return "".join(f"{indent}{name}: {value};\n" for name, value in variables.items())


def compile_css(tokens: dict[str, dict]) -> str:
    """The runtime stylesheet for a *complete* token set (light, dark and system modes)."""
    light = {**tk.shared_variables(tokens), **tk.mode_variables(tokens, "light")}
    dark = tk.mode_variables(tokens, "dark")
    return (
        _HEADER
        + f"{LIGHT_SELECTOR} {{\n  color-scheme: light;\n{_declarations(light)}}}\n"
        + f"{DARK_SELECTOR} {{\n  color-scheme: dark;\n{_declarations(dark)}}}\n"
        + "@media (prefers-color-scheme: dark) {\n"
        + f"  {SYSTEM_SELECTOR} {{\n    color-scheme: dark;\n{_declarations(dark, '    ')}  }}\n"
        + "}\n"
    )


def css_hash(css: str) -> str:
    return hashlib.sha256(css.encode("utf-8")).hexdigest()[:16]


def derived_variables() -> dict[str, str]:
    """Status tints derived *in the browser* from the status/surface/foreground colours.

    Declared once in ``tailwind/theme-defaults.css`` on ``:root`` **and** ``[data-theme]`` so a
    preview container of another mode re-derives them from its own colours.  The percentages
    are the shared constants the contrast checks use.
    """
    variables: dict[str, str] = {}
    for status in tk.STATUS_NAMES:
        base = f"var(--color-{status})"
        variables[f"--color-{status}-soft"] = f"color-mix(in srgb, {base} {STATUS_SOFT_PERCENT}%, var(--color-surface))"
        variables[f"--color-{status}-border"] = f"color-mix(in srgb, {base} {STATUS_BORDER_PERCENT}%, var(--color-surface))"
        variables[f"--color-{status}-text"] = f"color-mix(in srgb, {base} {STATUS_TEXT_PERCENT}%, var(--color-foreground))"
    return variables


def compile_defaults_for_tailwind() -> str:
    """The generated ``tailwind/theme-defaults.css`` (fallback when no theme stylesheet loads).

    Light values go in ``@theme static`` so Tailwind generates ``bg-primary`` & co. and emits
    every variable; dark/system values are plain base-layer rules.  A test keeps the committed
    file identical to this output, so the fallback can never drift from the registry.
    """
    tokens = tk.default_tokens()
    light = {**tk.shared_variables(tokens), **tk.mode_variables(tokens, "light")}
    dark = tk.mode_variables(tokens, "dark")
    return (
        "/* Generated by `python manage.py render_theme_defaults` - do not edit. */\n"
        "/* Built-in design-token defaults: the fallback under every theme stylesheet. */\n"
        f"@theme static {{\n{_declarations(light)}{_declarations(derived_variables())}}}\n\n"
        "@layer base {\n"
        f"  :root, [data-theme] {{\n{_declarations(derived_variables(), '    ')}  }}\n"
        f'  [data-theme="light"] {{\n    color-scheme: light;\n{_declarations(light, "    ")}  }}\n'
        f"  {DARK_SELECTOR} {{\n    color-scheme: dark;\n{_declarations(dark, '    ')}  }}\n"
        "  @media (prefers-color-scheme: dark) {\n"
        f"    {SYSTEM_SELECTOR} {{\n      color-scheme: dark;\n{_declarations(dark, '      ')}    }}\n"
        "  }\n"
        "}\n"
    )
