"""``/api/v1/reports/…`` (Phase 19): the report catalogue, validation, paginated results, exports, saved configurations and the caller's run history.

Thin adapters over ``apps.reporting.services`` - the same code as the web screens.  Every report, filter, column, sort and grouping is validated against the server-side registry
(unknown ones are 400s, never ORM lookups); scope is applied by the owning modules' selectors before any filter; the active organization is validated against the caller's access.
Exports return a *run*: small ones are ready immediately, large ones are generated by a Phase 18 job.  Files are only downloadable by their requester, re-authorized at download.
"""

from __future__ import annotations

from typing import Any

from django.core.exceptions import PermissionDenied as DjangoPermissionDenied
from django.http import HttpResponse
from drf_spectacular.utils import extend_schema
from rest_framework import serializers
from rest_framework.exceptions import NotFound, PermissionDenied
from rest_framework.request import Request
from rest_framework.response import Response
from rest_framework.views import APIView

from apps.accounts.context import get_active_organization
from apps.api.exceptions import ConflictAPIException, StructuredValidationError
from apps.api.permissions import IsActiveUser
from apps.reporting import constants as k
from apps.reporting import policies, registry, services
from apps.reporting.errors import ReportConflict, ReportError
from apps.reporting.services import saved as saved_service


def run_service(call):  # noqa: ANN001, ANN201
    try:
        return call()
    except DjangoPermissionDenied as exc:
        raise PermissionDenied from exc
    except ReportConflict as exc:
        raise ConflictAPIException(detail={"detail": exc.message, "code": exc.code}) from exc
    except ReportError as exc:
        raise StructuredValidationError({"__all__": [exc.message]}, extra={"code": exc.code, **exc.extra}) from exc


class _Strict(serializers.Serializer):
    def to_internal_value(self, data):  # noqa: ANN001, ANN201
        unknown = {key: "This field cannot be set." for key in data if key not in self.fields}
        if unknown:
            raise serializers.ValidationError(unknown)
        return super().to_internal_value(data)


class RequestIn(_Strict):
    filters = serializers.DictField(required=False, default=dict)
    columns = serializers.ListField(child=serializers.CharField(max_length=40), required=False, default=list, max_length=40)
    sort = serializers.CharField(required=False, allow_blank=True, default="", max_length=41)
    group_by = serializers.CharField(required=False, allow_blank=True, default="", max_length=30)


class RunIn(RequestIn):
    page = serializers.IntegerField(required=False, default=1, min_value=1)
    page_size = serializers.IntegerField(required=False, default=k.PAGE_SIZE, min_value=1, max_value=k.MAX_PAGE_SIZE)


class ExportIn(RequestIn):
    format = serializers.ChoiceField(choices=k.Format.choices)


class SavedIn(RequestIn):
    name = serializers.CharField(max_length=120)
    description = serializers.CharField(max_length=500, required=False, allow_blank=True, default="")
    report = serializers.CharField(max_length=60, required=False)
    visibility = serializers.ChoiceField(choices=k.Visibility.choices, required=False, default=k.Visibility.PRIVATE)
    default_format = serializers.ChoiceField(choices=k.Format.choices, required=False, allow_blank=True, default="")


def organization(request: Request) -> Any:
    org = get_active_organization(request._request)
    if org is None or not policies.can_report(request.user, org):
        raise PermissionDenied
    return org


def _raw(data: dict[str, Any]) -> dict[str, Any]:
    return {"filters": data.get("filters"), "columns": data.get("columns"), "sort": data.get("sort"), "group_by": data.get("group_by")}


def _json_value(value: Any) -> Any:
    from datetime import date, datetime, timedelta
    from decimal import Decimal

    if isinstance(value, Decimal):
        return float(value)
    if isinstance(value, timedelta):
        return round(value.total_seconds() / 60, 1)
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    return value


def _run(r) -> dict[str, Any]:  # noqa: ANN001
    return {"id": str(r.pk), "report": r.report_code, "report_version": r.report_version, "format": r.format, "status": r.status, "row_count": r.row_count, "created_at": r.created_at,
            "started_at": r.started_at, "finished_at": r.finished_at, "duration_ms": r.duration_ms, "expires_at": r.expires_at, "error": r.error_message, "correlation_id": r.correlation_id,
            "downloadable": r.status == k.RunStatus.SUCCEEDED, "origin": r.origin}


def _saved(s, user: Any) -> dict[str, Any]:  # noqa: ANN001
    return {"id": str(s.pk), "name": s.name, "description": s.description, "report": s.report_code, "report_version": s.report_version, "filters": s.filters, "columns": s.columns, "sort": s.sort,
            "group_by": s.group_by, "default_format": s.default_format, "visibility": s.visibility, "owner_is_me": s.owner_id == user.pk, "updated_at": s.updated_at}


class ReportListView(APIView):
    permission_classes = [IsActiveUser]

    @extend_schema(responses={200: dict}, tags=["reports"])
    def get(self, request: Request) -> Response:
        org = organization(request)
        people = policies.can_see_people(request.user, org)
        return Response({"reports": [registry.describe(r, people=people) for r in policies.visible_reports(request.user, org)], "can_export": policies.can_export(request.user, org)})


class ReportDetailView(APIView):
    permission_classes = [IsActiveUser]

    @extend_schema(responses={200: dict}, tags=["reports"])
    def get(self, request: Request, code: str) -> Response:
        org = organization(request)
        report = registry.get(code)
        if report is None or not policies.can_use_report(request.user, org, report):
            raise NotFound
        return Response(registry.describe(report, people=policies.can_see_people(request.user, org)))


class ValidateView(APIView):
    permission_classes = [IsActiveUser]

    @extend_schema(request=RequestIn, responses={200: dict}, tags=["reports"])
    def post(self, request: Request, code: str) -> Response:
        org = organization(request)
        data = RequestIn(data=request.data)
        data.is_valid(raise_exception=True)
        return Response({"valid": True, "normalized": run_service(lambda: saved_service.validate(request.user, org, code, _raw(data.validated_data)))})


class RunView(APIView):
    permission_classes = [IsActiveUser]

    @extend_schema(request=RunIn, responses={200: dict}, tags=["reports"])
    def post(self, request: Request, code: str) -> Response:
        org = organization(request)
        data = RunIn(data=request.data)
        data.is_valid(raise_exception=True)
        body = data.validated_data
        result = run_service(lambda: services.run(request.user, org, code, _raw(body), page=body["page"], page_size=body["page_size"]))
        columns = [{"key": c.key, "label": c.label, "type": c.kind} for c in result.columns]
        rows = [{c.key: _json_value(row.get(c.key)) for c in result.columns} for row in result.rows]
        response = Response({"report": result.report.code, "version": result.report.version, "columns": columns, "rows": rows, "generated_at": result.generated_at, "applied": result.params.normalized(),
                             "period": {"from": result.params.start, "to_exclusive": result.params.end}, "truncated": result.truncated})
        response.data = {"data": response.data["rows"], "meta": {"count": result.total, "page": result.page, "page_size": result.page_size, "pages": result.pages, **{key: v for key, v in response.data.items() if key != "rows"}}}
        response.use_envelope = False
        return response


class ExportView(APIView):
    permission_classes = [IsActiveUser]

    @extend_schema(request=ExportIn, responses={200: dict, 202: dict}, tags=["reports"])
    def post(self, request: Request, code: str) -> Response:
        org = organization(request)
        data = ExportIn(data=request.data)
        data.is_valid(raise_exception=True)
        body = data.validated_data
        run = run_service(lambda: services.request_export(request.user, org, code, _raw(body), body["format"]))
        return Response(_run(run), status=200 if run.status in (k.RunStatus.SUCCEEDED, k.RunStatus.FAILED) else 202)


class RunListView(APIView):
    permission_classes = [IsActiveUser]

    @extend_schema(responses={200: dict}, tags=["reports"])
    def get(self, request: Request) -> Response:
        org = organization(request)
        qs = services.runs_visible_to(request.user, org).order_by("-created_at")
        try:
            limit, offset = max(1, min(int(request.query_params.get("limit", 25)), 100)), max(0, int(request.query_params.get("offset", 0)))
        except ValueError as exc:
            raise StructuredValidationError({"limit": ["Use whole numbers for limit and offset."]}) from exc
        return Response({"count": qs.count(), "results": [_run(r) for r in qs[offset:offset + limit]]})


class RunDetailView(APIView):
    permission_classes = [IsActiveUser]

    @extend_schema(responses={200: dict}, tags=["reports"])
    def get(self, request: Request, pk: str) -> Response:
        organization(request)
        run = services.get_run(request.user, pk)
        if run is None:
            raise NotFound
        return Response(_run(run))


class DownloadView(APIView):
    permission_classes = [IsActiveUser]

    @extend_schema(responses={200: bytes}, tags=["reports"])
    def get(self, request: Request, pk: str) -> HttpResponse:
        organization(request)
        run = services.get_run(request.user, pk)
        if run is None:
            raise NotFound
        data, mime, filename = run_service(lambda: services.open_artifact(request.user, run))
        response = HttpResponse(data, content_type=mime)
        response["Content-Disposition"] = f'attachment; filename="{filename}"'
        response["Cache-Control"] = "private, no-store"
        response["X-Content-Type-Options"] = "nosniff"
        return response


class SavedListView(APIView):
    permission_classes = [IsActiveUser]

    @extend_schema(responses={200: dict}, tags=["reports"])
    def get(self, request: Request) -> Response:
        org = organization(request)
        rows = saved_service.visible_to(request.user, org).order_by("name")
        return Response({"count": rows.count(), "results": [_saved(s, request.user) for s in rows[:200]]})

    @extend_schema(request=SavedIn, responses={201: dict}, tags=["reports"])
    def post(self, request: Request) -> Response:
        org = organization(request)
        data = SavedIn(data=request.data)
        data.is_valid(raise_exception=True)
        body = dict(data.validated_data)
        code = body.pop("report", None)
        if not code:
            raise StructuredValidationError({"report": ["This field is required."]})
        return Response(_saved(run_service(lambda: saved_service.save(request.user, org, code, {**_raw(body), **{key: body[key] for key in ("name", "description", "visibility", "default_format")}})), request.user), status=201)


class SavedDetailView(APIView):
    permission_classes = [IsActiveUser]

    def _get(self, request: Request, pk: str):  # noqa: ANN202
        org = organization(request)
        saved = saved_service.get(request.user, org, pk)
        if saved is None:
            raise NotFound
        return org, saved

    @extend_schema(responses={200: dict}, tags=["reports"])
    def get(self, request: Request, pk: str) -> Response:
        _org, saved = self._get(request, pk)
        return Response(_saved(saved, request.user))

    @extend_schema(request=SavedIn, responses={200: dict}, tags=["reports"])
    def put(self, request: Request, pk: str) -> Response:
        org, saved = self._get(request, pk)
        data = SavedIn(data=request.data)
        data.is_valid(raise_exception=True)
        body = data.validated_data
        if body.get("report") not in (None, saved.report_code):
            raise StructuredValidationError({"report": ["A saved report cannot change its report."]})
        return Response(_saved(run_service(lambda: saved_service.save(request.user, org, saved.report_code, {**_raw(body), **{key: body[key] for key in ("name", "description", "visibility", "default_format")}}, saved=saved)), request.user))

    @extend_schema(responses={204: None}, tags=["reports"])
    def delete(self, request: Request, pk: str) -> Response:
        _org, saved = self._get(request, pk)
        run_service(lambda: saved_service.delete(request.user, saved))
        return Response(status=204)


class SavedActionView(APIView):
    permission_classes = [IsActiveUser]

    @extend_schema(request=RunIn, responses={200: dict}, tags=["reports"])
    def post(self, request: Request, pk: str, action: str) -> Response:
        org = organization(request)
        saved = saved_service.get(request.user, org, pk)
        if saved is None or action not in {"run", "duplicate"}:
            raise NotFound
        if action == "duplicate":
            return Response(_saved(run_service(lambda: saved_service.duplicate(request.user, org, saved)), request.user), status=201)
        data = RunIn(data={key: value for key, value in request.data.items() if key in ("page", "page_size")})
        data.is_valid(raise_exception=True)
        result = run_service(lambda: saved_service.run(request.user, org, saved, page=data.validated_data["page"], page_size=data.validated_data["page_size"]))
        rows = [{c.key: _json_value(row.get(c.key)) for c in result.columns} for row in result.rows]
        response = Response({"data": rows, "meta": {"count": result.total, "page": result.page, "pages": result.pages}})
        response.use_envelope = False
        return response
